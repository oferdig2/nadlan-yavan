(function (window) {
  "use strict";

  var Nadlan = window.Nadlan = window.Nadlan || {};

  function escapeHtml(value) {
    return String(value === null || value === undefined ? "" : value)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
  }

  // Same rules as TextNormalize.ParseDecimal on the server: "120,000" / "1,234.5" = thousands separators,
  // a single comma with no dot ("0,8") = decimal comma. Returns null when empty, NaN when unreadable.
  function parseNumber(text) {
    var t = String(text === null || text === undefined ? "" : text).trim();
    if (t === "") { return null; }
    if (/^-?\d{1,3}(,\d{3})+(\.\d+)?$/.test(t)) {
      t = t.replace(/,/g, "");
    } else if ((t.match(/,/g) || []).length === 1 && t.indexOf(".") < 0) {
      t = t.replace(",", ".");
    }
    return /^-?\d+(\.\d+)?$/.test(t) ? Number(t) : NaN;
  }

  Nadlan.format = {
    escapeHtml: escapeHtml,
    parseNumber: parseNumber,

    sqm: function (value) {
      return value === null || value === undefined ? "—" : Number(value).toLocaleString("en-US") + " m²";
    },

    price: function (amount, currency) {
      if (amount === null || amount === undefined) { return "<span class=\"muted\">No price</span>"; }
      var symbol = currency === "EUR" ? "€" : escapeHtml(currency || "") + " ";
      return symbol + Number(amount).toLocaleString("en-US", { maximumFractionDigits: 0 });
    },

    statusBadge: function (name, color) {
      var safeColor = /^#[0-9a-fA-F]{6}$/.test(color || "") ? color : "#64748b";
      return "<span class=\"badge\" style=\"background:" + safeColor + "22;color:" + safeColor + "\">" + escapeHtml(name) + "</span>";
    },

    text: function (value) {
      return value === null || value === undefined || value === "" ? "—" : escapeHtml(value);
    },

    // KAEK with an explicit marker when the system invented it.
    registryId: function (registryId, isProvisional) {
      var html = "<span class=\"kaek\">" + escapeHtml(registryId || "—") + "</span>";
      if (isProvisional) {
        html += " <span class=\"badge badge-warn\" title=\"Real KAEK unknown - this id was generated by the system\">Provisional KAEK</span>";
      }
      return html;
    }
  };
})(window);
